// EN: The smallest map generator (Docs/SandboxPlan.md, step G9): a chain of REGISTERED steps run once when a world is made, each with its own random stream derived from (seed, step index, step name), so adding or
//     removing a step never changes what the others draw. The numbers are integer-hashed (SplitMix64) so one seed gives one map; interpolation uses double arithmetic, so "the same map" is promised on one machine
//     (the world is made once on the host and then travels as cells, never regenerated by a client). Two sample steps: `noise_ground` (a second ground type where smooth noise passes a threshold), `noise_height`
//     (smooth hills), and `stamp` (a stamp from a library, put down at a cell). Content modules add steps through `PNGridMapSteps.Register`. Pure C#.
// VI: Bộ sinh map nhỏ nhất: chuỗi bước ĐÃ ĐĂNG KÝ chạy một lần lúc tạo world, mỗi bước có luồng ngẫu nhiên riêng suy từ (seed, thứ tự, tên) nên thêm/bớt bước không đổi kết quả bước khác. Ba bước mẫu: `noise_ground`, `noise_height`, `stamp`.
public sealed class PNGridRandom
{
    private const ulong Gamma = 0x9E3779B97F4A7C15UL;
    private ulong state;
    public PNGridRandom(ulong seed) { state = Mix(seed); }
    public static ulong Mix(ulong value)
    {
        unchecked { value = (value ^ (value >> 30)) * 0xBF58476D1CE4E5B9UL; value = (value ^ (value >> 27)) * 0x94D049BB133111EBUL; return value ^ (value >> 31); }
    }
    public ulong Next() { unchecked { state += Gamma; } return Mix(state); }
    public double NextDouble() => (Next() >> 11) * (1.0 / 9007199254740992.0);
    public int NextInt(int exclusiveMax)
    {
        if (exclusiveMax < 1) throw new ArgumentOutOfRangeException(nameof(exclusiveMax));
        ulong bound = (ulong)exclusiveMax, limit = ulong.MaxValue - ulong.MaxValue % bound, value;
        do value = Next(); while (value >= limit);
        return (int)(value % bound);
    }
    public static ulong Fnv(string text)
    {
        unchecked { ulong h = 14695981039346656037UL; foreach (char c in text) { h ^= c; h *= 1099511628211UL; } return h; }
    }
}

public sealed class PNGridGenContext
{
    public PNGridMapDoc Doc { get; }
    public PNGridRandom Random { get; }
    public ulong StepSeed { get; }
    public Func<string, PNGridStamp> Stamps { get; }
    public PNGridGenContext(PNGridMapDoc doc, PNGridRandom random, ulong stepSeed, Func<string, PNGridStamp> stamps) { Doc = doc; Random = random; StepSeed = stepSeed; Stamps = stamps; }

    // Smooth value noise in [0, 1) at a point given in metres, `scale` metres per lattice step.
    public double Noise(double x, double z, double scale)
    {
        double fx = x / scale, fz = z / scale; long ix = (long)Math.Floor(fx), iz = (long)Math.Floor(fz);
        double tx = fx - ix, tz = fz - iz; tx = tx * tx * (3 - 2 * tx); tz = tz * tz * (3 - 2 * tz);
        double a = Lattice(ix, iz), b = Lattice(ix + 1, iz), c = Lattice(ix, iz + 1), d = Lattice(ix + 1, iz + 1);
        return (a + (b - a) * tx) + ((c + (d - c) * tx) - (a + (b - a) * tx)) * tz;
    }
    private double Lattice(long x, long z) => (PNGridRandom.Mix(StepSeed ^ PNGridRandom.Mix((ulong)x * 0x9E3779B97F4A7C15UL + (ulong)z * 0xC2B2AE3D27D4EB4FUL)) >> 11) * (1.0 / 9007199254740992.0);
}

public delegate void PNGridMapStepRun(PNGridGenContext context, JObject args);

public sealed class PNGridMapStep
{
    public string Name { get; }
    public string[] Fields { get; }
    public PNGridMapStepRun Run { get; }
    public PNGridMapStep(string name, string[] fields, PNGridMapStepRun run) { Name = name; Fields = fields; Run = run; }
}

// The registered steps. Registering the same name twice is refused; a step lists its argument fields so a mistyped one is refused instead of ignored.
public static class PNGridMapSteps
{
    private static readonly Dictionary<string, PNGridMapStep> steps = new Dictionary<string, PNGridMapStep>(StringComparer.Ordinal);
    static PNGridMapSteps()
    {
        Register(new PNGridMapStep("noise_ground", new[] { "ground", "scale", "threshold" }, NoiseGround));
        Register(new PNGridMapStep("noise_height", new[] { "scale", "amplitude" }, NoiseHeight));
        Register(new PNGridMapStep("stamp", new[] { "stamp", "x", "z" }, StampStep));
    }
    public static void Register(PNGridMapStep step)
    {
        if (step == null) throw new ArgumentNullException(nameof(step));
        if (!PNGridMapMeta.ValidName(step.Name)) throw new ArgumentException("A step name is lower-case words.");
        lock (steps) { if (steps.ContainsKey(step.Name)) throw new InvalidOperationException("Map step " + step.Name + " is already registered."); steps[step.Name] = step; }
    }
    public static PNGridMapStep Get(string name) { lock (steps) return steps.TryGetValue(name ?? "", out var step) ? step : null; }

    private static double Number(JObject args, string field, double fallback, double min, double max)
    {
        var token = args[field];
        if (token == null) return fallback;
        if (token.Type != JTokenType.Integer && token.Type != JTokenType.Float) throw new FormatException("Step argument " + field + " must be a number.");
        double v = (double)token;
        if (double.IsNaN(v) || v < min || v > max) throw new FormatException("Step argument " + field + " is " + min + " to " + max + ".");
        return v;
    }

    private static void NoiseGround(PNGridGenContext c, JObject args)
    {
        string ground = args["ground"]?.Type == JTokenType.String ? (string)args["ground"] : throw new FormatException("noise_ground needs a ground id.");
        int index = c.Doc.Palette.ToList().IndexOf(ground);
        if (index < 0) throw new FormatException("noise_ground: the world has no ground type " + ground + ".");
        double scale = Number(args, "scale", 16, 2, 512), threshold = Number(args, "threshold", .5, 0, 1);
        var data = c.Doc.Data; float cell = data.CellSize * data.GroundFactor;
        var edits = new List<PNGridEdit>();
        for (int gz = 0; gz < data.GroundRows; gz++) for (int gx = 0; gx < data.GroundColumns; gx++)
            if (c.Noise((gx + .5) * cell, (gz + .5) * cell, scale) >= threshold) edits.Add(new PNGridEdit(PNGridEditKind.Ground, gx * data.GroundFactor, gz * data.GroundFactor, index));
        c.Doc.Edit("noise ground", edits);
    }

    private static void NoiseHeight(PNGridGenContext c, JObject args)
    {
        double scale = Number(args, "scale", 24, 2, 512), amplitude = Number(args, "amplitude", 4, 0, 40);   // amplitude in height steps (0.25 m)
        var data = c.Doc.Data; var edits = new List<PNGridEdit>();
        for (int z = 0; z < data.Depth; z++) for (int x = 0; x < data.Width; x++)
            edits.Add(new PNGridEdit(PNGridEditKind.Height, x, z, (int)Math.Round(c.Noise((x + .5) * data.CellSize, (z + .5) * data.CellSize, scale) * amplitude)));
        c.Doc.Edit("noise height", edits);
    }

    private static void StampStep(PNGridGenContext c, JObject args)
    {
        string name = args["stamp"]?.Type == JTokenType.String ? (string)args["stamp"] : throw new FormatException("stamp needs a stamp name.");
        if (args["x"]?.Type != JTokenType.Integer || args["z"]?.Type != JTokenType.Integer) throw new FormatException("stamp needs integer cell coordinates x and z.");
        var stamp = c.Stamps?.Invoke(name) ?? throw new FormatException("stamp: there is no stamp named " + name + ".");
        c.Doc.Paste(stamp, (int)args["x"], (int)args["z"]);
    }
}

public static class PNGridMapGen
{
    public const int MaxSteps = 64;

    // Checks a step list without running it (known step, only known fields).
    public static void Validate(JArray steps)
    {
        if (steps == null) throw new ArgumentNullException(nameof(steps));
        if (steps.Count > MaxSteps) throw new FormatException("A generator chain has at most " + MaxSteps + " steps.");
        foreach (var item in steps)
        {
            var o = item as JObject ?? throw new FormatException("A generator step is an object.");
            string name = o["step"]?.Type == JTokenType.String ? (string)o["step"] : throw new FormatException("A generator step needs its name in \"step\".");
            var step = PNGridMapSteps.Get(name) ?? throw new FormatException("Unknown generator step: " + name);
            foreach (var p in o.Properties()) if (p.Name != "step" && Array.IndexOf(step.Fields, p.Name) < 0) throw new FormatException("Step " + name + " has no argument " + p.Name + ".");
        }
    }

    // Runs the chain on a document as ONE undoable step. The same seed and steps give the same cells.
    public static void Run(PNGridMapDoc doc, JArray steps, long seed, Func<string, PNGridStamp> stamps = null)
    {
        if (doc == null) throw new ArgumentNullException(nameof(doc));
        Validate(steps);
        doc.Compound("generate", () =>
        {
            for (int i = 0; i < steps.Count; i++)
            {
                var o = (JObject)steps[i]; string name = (string)o["step"];
                ulong stepSeed = PNGridRandom.Mix(unchecked((ulong)seed) ^ PNGridRandom.Fnv(name) ^ PNGridRandom.Mix((ulong)(i + 1) * 0xD6E8FEB86659FD93UL));
                PNGridMapSteps.Get(name).Run(new PNGridGenContext(doc, new PNGridRandom(stepSeed), stepSeed, stamps), o);
            }
        });
    }
}
